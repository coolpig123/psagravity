"""Generated reports: per-fire README and the all-fires summary (docs/fires_summary.md + .csv).

    python -m firedata.report readme crosswhite
    python -m firedata.report summary bug_fire crosswhite colwash biscar

A fire README is only (re)written when it is missing or was generated before (it carries the
GENERATED marker); hand-written READMEs (e.g. bug_fire) are left alone.
"""
from __future__ import annotations

import argparse
import csv
import json

import pandas as pd

from .config import FIRES, FireConfig, REPO_ROOT
from .metrics import DEFINITIONS, compute

GENERATED = "<!-- generated by firedata.report; edit FireConfig.notes instead -->"
METRIC_LABEL = {
    "feds_iou": "IoU", "feds_area_ratio": "area ratio", "viirs_cover": "covers", "viirs_inside": "inside",
    "goes_cover": "covers", "goes_inside": "inside", "ignition_error_min": "first detection",
    "ignition_dist_km": "from origin",
}


def _fmt_metric(k: str, v) -> str:
    if v is None:
        return f"{METRIC_LABEL[k]} N/A"
    if k == "ignition_error_min":
        sign = "+" if v >= 0 else "−"
        a = abs(v)
        return f"first detection {sign}{a // 60}h{a % 60:02d}m" if a >= 60 else f"first detection {sign}{a} min"
    if k == "ignition_dist_km":
        return f"{v:g} km from origin"
    return f"{METRIC_LABEL[k]} {v:g}%"


def _t(s) -> str:
    if s in (None, "None", "NaT", "nan"):
        return "—"
    return f"{pd.Timestamp(s):%Y-%m-%d %H:%M} UTC"


def fire_readme(F: FireConfig, m: dict | None = None) -> str:
    P = F.root / "processed"
    s = json.loads((P / "summary.json").read_text())
    m = m or compute(F)
    w = s["wfigs"]
    pairs = pd.read_csv(P / "nisar_pairs.csv") if (P / "nisar_pairs.csv").exists() else pd.DataFrame()
    first = {k: v for k, v in s.get("first_detection_utc", {}).items()}
    fd = min(first.values()) if first else None
    L = [GENERATED, f"# {F.name}: fire-progression ground truth", "",
         f"Built with `python scripts/build_ground_truth.py {F.slug}` (raw downloads cached in `raw/`, not committed).", "",
         "## Key facts", "", "| | Value | Source |", "|---|---|---|",
         f"| Incident ID | {w['unique_fire_id']} | NIFC WFIGS |",
         f"| Discovery (ignition) | {_t(w['discovery_utc'])} | NIFC WFIGS |",
         f"| Point of origin | {w['origin_lat']}, {w['origin_lon']} | NIFC WFIGS |",
         f"| First satellite detection | {_t(fd)} | " + ", ".join(f"{k}: {_t(v)}" for k, v in sorted(first.items())) + " |",
         f"| Growth ended | ~{_t(s.get('growth_end_utc'))} | {s.get('growth_end_rule', '')} |",
         f"| Final size | {w['final_acres']:,.0f} acres ({m['official_area_km2']} km²), perimeter dated {_t(w['perimeter_date_utc'])} | NIFC WFIGS |",
         f"| Contained | {_t(w['containment_utc'])} | NIFC WFIGS |",
         f"| Fire out | {_t(w['fire_out_utc'])} | NIFC WFIGS |"]
    for mi in s.get("merged_incidents", []):
        L.append(f"| Merged incident | {mi['IncidentName']} ({mi['UniqueFireIdentifier']}, {float(mi['IncidentSize'] or 0):,.0f} acres, "
                 f"discovered {_t(mi['FireDiscoveryDateTime'])}) | NIFC WFIGS |")
    if F.notes:
        L += ["", "## Notes and data mismatches", ""] + [f"- {n}" for n in F.notes]
    nb = [n for n in s.get("neighbour_fires", []) if float(n["poly_GISAcres"] or 0) >= 100]
    if nb:
        L += ["", "Neighbouring fires in the search box (detections closer to them are excluded): " +
              ", ".join(f"{n['poly_IncidentName']} ({float(n['poly_GISAcres']):,.0f} ac)" for n in nb) + "."]
    L += ["", "## Data and agreement with the official perimeter", "",
          "| Item | Source | Time range | Resolution | Update rate | Coverage | Agreement |",
          "|---|---|---|---|---|---|---|"]
    for name, it in m["items"].items():
        if it.get("reference"):
            agree = "reference"
        elif it.get("metrics"):
            agree = "; ".join(_fmt_metric(k, v) for k, v in it["metrics"].items())
        else:
            agree = f"N/A: {it.get('na', '')}"
        L.append(f"| {name} | {it['source']} | {it.get('time_range', '—')} | {it.get('resolution', '—')} | "
                 f"{it.get('update_rate', '—')} | {it.get('coverage', it.get('na', '—'))} | {agree} |")
    L += ["", f"FEDS ∪ VIIRS ∪ GOES together cover **{m['all_cover']}%** of the official area. "
          "Metric definitions: `docs/fires_summary.md`."]
    if len(pairs):
        L += ["", "## NISAR same-track pairs", "", "| Track | Pre-fire | Post-fire | Gap |", "|---|---|---|---|"]
        L += [f"| {r.track_id} | {_t(r.pre_utc)} | {_t(r.post_utc)} | {r.gap_days:g} days |" for r in pairs.itertuples()]
    L += ["", "## Ground truth for calibration", "",
          "Same decision as the Bug Fire: **extent** = official WFIGS final perimeter; **timing** = VIIRS + GOES "
          "arrival times (`fire_points.*`, `ambiguous = False`); **FEDS 12 h perimeters** = direction/shape only, "
          "their area is a lower bound.", "",
          "## Outputs", "",
          "- `processed/fire_points.csv|parquet`: `time_utc, lat, lon, frp_mw, source, confidence, ambiguous, ...`",
          "- `processed/feds_perimeters_12h.csv|geojson`, `feds_fireline_12h.geojson`, `feds_fire_ids_selected.csv`",
          "- `processed/frp_timeseries.csv`, `nisar_passes.csv`, `nisar_pairs.csv`, `metrics.json`, `summary.json`",
          "- `processed/wfigs_final_perimeter.geojson`, `wfigs_neighbour_perimeters.geojson`",
          "- `figures/`: perimeters every 12 h, FEDS vs official, burned area, FRP vs time, VIIRS FRP map, "
          f"`{F.slug}_spread.html` (interactive, `python -m firedata.web {F.slug}`)"]
    return "\n".join(L) + "\n"


def write_readme(fire: str) -> bool:
    F = FIRES[fire]
    path = F.root / "README.md"
    if path.exists() and GENERATED not in path.read_text():
        print(f"  {path} is hand-written; not overwritten")
        return False
    path.write_text(fire_readme(F))
    print(f"  wrote {path}")
    return True


def write_summary(fires: list[str], in_progress: list[str] = ()) -> None:
    docs = REPO_ROOT / "docs"
    rows, md = [], ["# Fire ground truth: data and agreement summary", "",
                    "One table per fire, one row per data item. Every agreement value is measured against the "
                    "**official final perimeter** (NIFC WFIGS). Definitions are below the tables.", ""]
    for fire in fires:
        F = FIRES[fire]
        m = compute(F)
        (F.root / "processed" / "metrics.json").write_text(json.dumps(m, indent=2, ensure_ascii=False))
        md += [f"## {F.name}", "",
               f"Official area {m['official_acres']:,} acres ({m['official_area_km2']} km²). "
               f"FEDS ∪ VIIRS ∪ GOES cover {m['all_cover']}% of it. Details: `data/fires/{fire}/README.md`.", "",
               "| Item | Source | Time range | Resolution | Update rate | Coverage | Agreement vs official |",
               "|---|---|---|---|---|---|---|"]
        for name, it in m["items"].items():
            if it.get("reference"):
                agree = "reference (100%)"
            elif it.get("metrics"):
                agree = "<br>".join(_fmt_metric(k, v) for k, v in it["metrics"].items())
            else:
                agree = f"N/A: {it.get('na', '')}"
            md.append(f"| {name} | {it['source']} | {it.get('time_range', '—')} | {it.get('resolution', '—')} | "
                      f"{it.get('update_rate', '—')} | {it.get('coverage', '—')} | {agree} |")
            base = {"fire": F.name, "item": name, "source": it["source"], "time_range": it.get("time_range", ""),
                    "resolution": it.get("resolution", ""), "update_rate": it.get("update_rate", ""),
                    "coverage": it.get("coverage", "")}
            if it.get("metrics"):
                for k, v in it["metrics"].items():
                    rows.append({**base, "metric": k, "value": "N/A" if v is None else v,
                                 "unit": "min" if k == "ignition_error_min" else "km" if k == "ignition_dist_km" else "%",
                                 "note": ""})
            else:
                rows.append({**base, "metric": "", "value": "reference" if it.get("reference") else "N/A",
                             "unit": "", "note": it.get("na", "")})
        rows.append({"fire": F.name, "item": "All sources", "source": "FEDS ∪ VIIRS ∪ GOES", "time_range": "",
                     "resolution": "", "update_rate": "", "coverage": "", "metric": "all_cover",
                     "value": m["all_cover"], "unit": "%", "note": ""})
        md.append("")
    for fire in in_progress:
        F = FIRES[fire]
        md += [f"## {F.name}", "", "**In progress**: data download / processing not finished yet. "
               "This table will be filled in when the pipeline run completes.", ""]
        rows.append({"fire": F.name, "item": "", "source": "", "time_range": "", "resolution": "", "update_rate": "",
                     "coverage": "", "metric": "", "value": "in progress", "unit": "", "note": "pipeline run not finished"})
    md += ["## Metric definitions", "",
           "W = official final perimeter (NIFC WFIGS). Pixel footprints: VIIRS = scan × track rectangle of each "
           "375 m detection; GOES = fixed-grid pixel corners. Points flagged `ambiguous` (also near a neighbouring "
           "fire) are excluded.", ""]
    md += [f"- **{k}**: {v}" for k, v in DEFINITIONS.items()]
    md += ["- **all_cover**: share of W covered by the union of the final FEDS perimeter, VIIRS footprints and GOES footprints.",
           "", "**Reading the numbers.** *cover* says how much of the official area a source saw; *inside* says how much of "
           "what it saw is inside the official perimeter (low = coarse pixels or detections spilling outside). GOES "
           "pixels are ~7 km², so GOES cover is high and GOES inside is low by construction. The official perimeter is "
           "an outer boundary and can include unburned islands, so no source is expected to reach 100%.", "",
           "**N/A rules.** NISAR burn-scar agreement is N/A until issue #7 is done. A metric is N/A when the source has "
           "no data for the fire (e.g. no FEDS id overlaps the official perimeter)."]
    (docs / "fires_summary.md").write_text("\n".join(md) + "\n")
    with open(docs / "fires_summary.csv", "w", newline="") as fh:
        wr = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        wr.writeheader()
        wr.writerows(rows)
    print(f"  wrote {docs / 'fires_summary.md'} and fires_summary.csv ({len(rows)} rows)")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("readme"); r.add_argument("fire", choices=FIRES)
    s = sub.add_parser("summary"); s.add_argument("fires", nargs="+", choices=FIRES)
    s.add_argument("--in-progress", nargs="*", default=[], choices=FIRES)
    a = ap.parse_args()
    write_readme(a.fire) if a.cmd == "readme" else write_summary(a.fires, a.in_progress)
